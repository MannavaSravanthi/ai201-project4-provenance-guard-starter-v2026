import config


def combine_signals(model_score: float, style_score: float) -> float:
    """
    Combine two 0–1 signals into one 0–1 score (higher = more likely AI).

    The rule:
      1. Weighted average: 0.6 x model + 0.4 x style. The model signal reads
         the whole text; the style signal is cheaper to fool, so it counts less.
      2. Disagreement rule: if the two signals are more than
         DISAGREEMENT_GAP apart, the system is not allowed to be confident.
         The score is pulled into the unsure band. Two methods disagreeing
         IS uncertainty, and a writer should never be called AI on the
         strength of one signal alone.
    """
    score = (config.WEIGHT_MODEL_SIGNAL * model_score
             + config.WEIGHT_STYLE_SIGNAL * style_score)

    if abs(model_score - style_score) > config.DISAGREEMENT_GAP:
        score = min(max(score, config.HUMAN_THRESHOLD + 0.01),
                    config.AI_THRESHOLD - 0.01)

    return round(min(max(score, 0.0), 1.0), 4)


LABEL_AI = (
    "This piece reads a lot like text generated by an AI tool. That's an "
    "automated guess, not a verdict, and it can be wrong. If you wrote this "
    "yourself, you can ask for a person to review it."
)
LABEL_HUMAN = (
    "We think this was written by a person."
)
LABEL_UNSURE = (
    "We couldn't tell whether this was written by a person or with an AI tool. "
    "That happens with lots of genuine writing, so we're not making any claim "
    "about it either way."
)


def score_to_label(score: float) -> tuple[str, str]:
    """
    Turn a score into (guess, label_text).

        score <  HUMAN_THRESHOLD           -> "human"
        HUMAN_THRESHOLD <= score <= AI_THRESHOLD -> "unsure"
        score >  AI_THRESHOLD              -> "ai"

    Every float in 0–1 falls in exactly one band, so there are no gaps.
    """
    if score > config.AI_THRESHOLD:
        return "ai", LABEL_AI
    if score < config.HUMAN_THRESHOLD:
        return "human", LABEL_HUMAN
    return "unsure", LABEL_UNSURE


def label_ranges() -> list[tuple[str, str]]:
    """
    The score range each label covers. Your README needs these beside the
    label text — given to you so the numbers can't drift apart from config.py.
    """
    return [
        ("high-confidence human", f"0.00 – {config.HUMAN_THRESHOLD:.2f}"),
        ("unsure", f"{config.HUMAN_THRESHOLD:.2f} – {config.AI_THRESHOLD:.2f}"),
        ("high-confidence AI", f"{config.AI_THRESHOLD:.2f} – 1.00"),
    ]
